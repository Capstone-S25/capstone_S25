        "    bw, bh = x2 - x1, y2 - y1\n",
        "    \n",
        "    cx1 = max(0, int(x1 - bw * pad_ratio))\n",
        "    cy1 = max(0, int(y1 - bh * pad_ratio))\n",
        "    cx2 = min(w, int(x2 + bw * pad_ratio))\n",
        "    cy2 = min(h, int(y2 + bh * pad_ratio))\n",
