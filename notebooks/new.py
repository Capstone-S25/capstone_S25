        "def run_rule_engine_v2(track_id, cls_name, conf, box, frame_id, stride=1, fps=30.0):\n",
        "    \"\"\"\n",
        "    Upgraded Loitering Gate:\n",
        "    1. Filters out low-confidence person detections.\n",
        "    2. Normalizes movement distance by person bounding-box height (perspective-invariant).\n",
        "    3. Deduplicates consecutive frames into a single VLM candidate event.\n",
        "    \"\"\"\n",
        "    global OLD_RULE_RAW_FRAME_TRIGGERS\n",
        "    if cls_name == \"person\" and conf < PERSON_CONF_MIN:\n",
        "        return False, None\n",
        "        \n",
        "    x1, y1, x2, y2 = box\n",
        "    cx, cy = (x1 + x2) / 2.0, (y1 + y2) / 2.0\n",
        "    person_h = max(1.0, float(y2 - y1))\n",
        "    \n",
        "    window_steps = max(5, int((5.0 * fps) / stride))  # 5 seconds of history\n",
        "    \n",
        "    if track_id not in TRACK_HISTORY:\n",
        "        TRACK_HISTORY[track_id] = {\n",
        "            \"start_frame\": frame_id,\n",
        "            \"positions\": [],\n",
        "            \"flagged\": False\n",
        "        }\n",
        "        \n",
        "    hist = TRACK_HISTORY[track_id]\n",
        "    hist[\"positions\"].append((cx, cy))\n",
        "    \n",
        "    if len(hist[\"positions\"]) > window_steps:\n",
        "        hist[\"positions\"].pop(0)\n",
        "        start_x, start_y = hist[\"positions\"][0]\n",
        "        raw_dist = float(np.hypot(cx - start_x, cy - start_y))\n",
        "        norm_dist = raw_dist / person_h\n",
        "        \n",
        "        duration_frames = frame_id - hist[\"start_frame\"]\n",
        "        \n",
        "        # Count what the old un-deduplicated rule would have triggered\n",
        "        if cls_name == \"person\" and duration_frames > 150 and raw_dist < 40:\n",
        "            OLD_RULE_RAW_FRAME_TRIGGERS += 1\n",
        "            \n",
        "        # Normalized trigger: displacement < 35% of person height over 5 seconds\n",
        "        if cls_name == \"person\" and duration_frames >= int(5.0 * fps) and norm_dist < 0.35:\n",
        "            if not hist[\"flagged\"]:\n",
        "                hist[\"flagged\"] = True\n",
        "                return True, {\n",
        "                    \"event_id\": f\"loiter_t{track_id}_f{frame_id}\",\n",
        "                    \"event_type\": \"sustained_loitering\",\n",
        "                    \"entity_id\": f\"person_{track_id}\",\n",
        "                    \"start_frame\": hist[\"start_frame\"],\n",
        "                    \"trigger_frame\": frame_id,\n",
        "                    \"timestamp_s\": round(frame_id / fps, 2),\n",
        "                    \"clip_window_s\": [round(max(0.0, (frame_id / fps) - CLIP_PADDING_SEC), 2),\n",
        "                                      round((frame_id / fps) + CLIP_PADDING_SEC, 2)],\n",
        "                    \"roi_box\": [int(x1), int(y1), int(x2), int(y2)],\n",
        "                    \"metrics\": {\"raw_disp_px\": round(raw_dist, 1), \"norm_disp_ratio\": round(norm_dist, 3)},\n",
        "                    \"vlm_prompt_hint\": \"A person has remained stationary for >5s. Verify if loitering/smoking/suspicious or normal waiting.\"\n",
        "                }\n",
        "        elif norm_dist >= 0.75:\n",
        "            hist[\"flagged\"] = False\n",
        "            \n",
        "    return False, None\n",
        "\n",
        "\n",
        "def check_unattended_objects_v2(boxes, classes, confs, model_names, curr_frame_id, stride=1, fps=30.0):\n",
        "    \"\"\"\n",
        "    Upgraded Unattended Object Gate:\n",
        "    1. Measures distance from bag center to person's FEET (cx, y2), normalized by person height.\n",
        "    2. Matches stationary bags across frames using bag diagonal size.\n",
        "    3. Deduplicates triggers so each abandoned bag only queries the VLM once.\n",
        "    \"\"\"\n",
        "    global OLD_RULE_RAW_FRAME_TRIGGERS\n",
        "    persons = []\n",
        "    bags = []\n",
        "    \n",
        "    for box, cls_idx, conf in zip(boxes, classes, confs):\n",
        "        cls_name = model_names[int(cls_idx)]\n",
        "        x1, y1, x2, y2 = box\n",
        "        cx, cy = (x1 + x2) / 2.0, (y1 + y2) / 2.0\n",
        "        \n",
        "        if cls_name == \"person\" and conf >= PERSON_CONF_MIN:\n",
        "            persons.append({\"feet\": (cx, float(y2)), \"center\": (cx, cy), \"height\": max(1.0, float(y2 - y1))})\n",
        "        elif cls_name in [\"backpack\", \"suitcase\", \"handbag\", \"bag\"]:\n",
        "            diag = max(1.0, float(np.hypot(x2 - x1, y2 - y1)))\n",
        "            bags.append({\"box\": [int(x1), int(y1), int(x2), int(y2)], \"center\": (cx, cy), \"diag\": diag, \"cls\": cls_name})\n",
        "            \n",
        "    seen_bag_ids = set()\n",
        "    new_events = []\n",
        "    unattended_thresh_frames = int(3.0 * fps)  # 3 seconds\n",
        "    grace_steps = max(3, int((0.5 * fps) / stride))\n",
        "    \n",
        "    for bag in bags:\n",
        "        bx, by = bag[\"center\"]\n",
        "        is_near_person = False\n",
        "        \n",
        "        for p in persons:\n",
        "            px, py_feet = p[\"feet\"]\n",
        "            if np.hypot(bx - px, by - py_feet) < (1.5 * p[\"height\"]):\n",
        "                is_near_person = True\n",
        "                break\n",
        "                \n",
        "        matched_bag_id = None\n",
        "        for b_id, data in UNATTENDED_ITEMS.items():\n",
        "            last_bx, last_by = data[\"last_center\"]\n",
        "            if np.hypot(bx - last_bx, by - last_by) < max(30.0, 1.2 * bag[\"diag\"]):\n",
        "                matched_bag_id = b_id\n",
        "                break\n",
        "                \n",
        "        if matched_bag_id is None:\n",
        "            matched_bag_id = f\"{bag['cls']}_{int(bx)}_{int(by)}\"\n",
        "            \n",
        "        seen_bag_ids.add(matched_bag_id)\n",
        "        \n",
        "        if not is_near_person:\n",
        "            if matched_bag_id not in UNATTENDED_ITEMS:\n",
        "                UNATTENDED_ITEMS[matched_bag_id] = {\n",
        "                    \"start_frame\": curr_frame_id,\n",
        "                    \"last_center\": (bx, by),\n",
        "                    \"box\": bag[\"box\"],\n",
        "                    \"missing_steps\": 0,\n",
        "                    \"flagged\": False\n",
        "                }\n",
        "            else:\n",
        "                UNATTENDED_ITEMS[matched_bag_id][\"last_center\"] = (bx, by)\n",
        "                UNATTENDED_ITEMS[matched_bag_id][\"box\"] = bag[\"box\"]\n",
        "                UNATTENDED_ITEMS[matched_bag_id][\"missing_steps\"] = 0\n",
        "                \n",
        "            item = UNATTENDED_ITEMS[matched_bag_id]\n",
        "            duration = curr_frame_id - item[\"start_frame\"]\n",
        "            \n",
        "            if duration > unattended_thresh_frames:\n",
        "                OLD_RULE_RAW_FRAME_TRIGGERS += 1\n",
        "                if not item[\"flagged\"]:\n",
        "                    item[\"flagged\"] = True\n",
        "                    new_events.append({\n",
        "                        \"event_id\": f\"unattended_{matched_bag_id}_f{curr_frame_id}\",\n",
        "                        \"event_type\": \"unattended_object\",\n",
        "                        \"entity_id\": matched_bag_id,\n",
        "                        \"start_frame\": item[\"start_frame\"],\n",
        "                        \"trigger_frame\": curr_frame_id,\n",
        "                        \"timestamp_s\": round(curr_frame_id / fps, 2),\n",
        "                        \"clip_window_s\": [round(max(0.0, (curr_frame_id / fps) - CLIP_PADDING_SEC), 2),\n",
        "                                          round((curr_frame_id / fps) + CLIP_PADDING_SEC, 2)],\n",
        "                        \"roi_box\": item[\"box\"],\n",
        "                        \"vlm_prompt_hint\": \"An object/bag was separated from its owner for >3s. Confirm if it is an unattended bag or a false detection.\"\n",
        "                    })\n",
        "        else:\n",
        "            if matched_bag_id in UNATTENDED_ITEMS:\n",
        "                del UNATTENDED_ITEMS[matched_bag_id]\n",
        "                \n",
        "    for b_id in list(UNATTENDED_ITEMS.keys()):\n",
        "        if b_id not in seen_bag_ids:\n",
        "            UNATTENDED_ITEMS[b_id][\"missing_steps\"] += 1\n",
        "            if UNATTENDED_ITEMS[b_id][\"missing_steps\"] > grace_steps:\n",
        "                del UNATTENDED_ITEMS[b_id]\n",
        "                \n",
        "    return (len(new_events) > 0), new_events\n",
        "\n",
        "print(\"Perspective-normalized & deduplicated rule engines initialized.\")"
